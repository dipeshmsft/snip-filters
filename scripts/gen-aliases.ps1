# Regenerates alias copies of user snip filters.
#
# snip matches the command name case-sensitively and does not strip .exe/.cmd,
# so "MSBuild.exe", "msbuild.exe" and "msbuild" each need their own filter.
# A canonical filter declares its extra names in a header comment:
#     # aliases: msbuild.exe, MSBuild.exe
# This script writes one "alias--<name>@<alias>.yaml" per alias (name and
# match.command rewritten, tests stripped) and deletes stale alias files.
# Re-run after editing any canonical filter.

param(
    [string]$Dir = (Join-Path $HOME '.config\snip\filters')
)

$ErrorActionPreference = 'Stop'
$utf8 = New-Object System.Text.UTF8Encoding($false)

Get-ChildItem $dir -Filter 'alias--*.yaml' | Remove-Item

$count = 0
foreach ($file in Get-ChildItem $dir -Filter '*.yaml') {
    $text = [IO.File]::ReadAllText($file.FullName)
    $m = [regex]::Match($text, '(?m)^# aliases:\s*(.+?)\s*$')
    if (-not $m.Success) { continue }

    $name = [regex]::Match($text, '(?m)^name:\s*"([^"]+)"').Groups[1].Value
    $body = [regex]::Replace($text, '(?m)^# aliases:.*\r?\n', '')
    $body = [regex]::Replace($body, '(?ms)^tests:.*\z', '')

    foreach ($alias in $m.Groups[1].Value.Split(',') | ForEach-Object { $_.Trim() } | Where-Object { $_ }) {
        $out = [regex]::Replace($body, '(?m)^name:\s*"[^"]+"', "name: `"$name@$alias`"")
        $out = [regex]::Replace($out, '(?m)^(  command:\s*)"[^"]+"', "`${1}`"$alias`"")
        $out = "# GENERATED by gen-aliases.ps1 from $($file.Name). Do not edit.`n" + $out
        $safe = ($alias -replace '[^A-Za-z0-9._-]', '_')
        $path = Join-Path $dir "alias--$name@$safe.yaml"
        $n = 2
        while (Test-Path $path) { $path = Join-Path $dir "alias--$name@$safe-$n.yaml"; $n++ }
        [IO.File]::WriteAllText($path, $out, $utf8)
        $count++
    }
}
Write-Output "Generated $count alias filter(s) in $dir"
